function GetMainGarageForSubGarage(subGarageName)
    for mainGarage, subGarages in pairs(Config.MainGarages) do
        for _, subGarage in ipairs(subGarages) do
            if subGarage == subGarageName then
                return mainGarage
            end
        end
    end
    return subGarageName 
end

function IsSubGarage(garageName)
    for _, subGarages in pairs(Config.MainGarages) do
        for _, subGarage in ipairs(subGarages) do
            if subGarage == garageName then
                return true
            end
        end
    end
    return false
end

exports('GetGarageLabelByIndex', function(index)
    for garageName, garageData in pairs(Config.Garages) do
        if garageName == index then
            return garageData.label
        end
    end
    return nil
end)

